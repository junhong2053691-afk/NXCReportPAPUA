// whatever is currently displayed. The source is kept in a WeakMap alongside
// the last value we wrote ("out"); if a node's current value differs from
// "out", a page script rewrote it and that new value becomes the source.
//
// This buys three things at once:
//   - no zh -> en -> zh drift (the old engine reverse-looked-up its own output,
//     and 13 English values map to more than one Chinese key)
//   - idempotence: running a pass twice is a no-op
//   - no need to disconnect the observer while writing; our own mutations are
//     recognised by the "out" check, so no page-script mutation is ever missed
// ---------------------------------------------------------------------------

const textState = new WeakMap(); // Text    -> { src, out }
const attrState = new WeakMap(); // Element -> { [attr]: { src, out } }
const I18N_SKIP_TAGS = /^(SCRIPT|STYLE|TEXTAREA|CODE|PRE)$/;

let i18nObserver = null;
let i18nTitleState = null;
let i18nDirty = new Set();
let i18nFullPass = false;
let i18nScheduled = false;

// Cached in memory as well as in localStorage: when storage is unavailable
// (private mode, blocked cookies) the write in applyLanguage throws, and
// reading the language back would strand the toggle on Chinese forever.
let i18nLang = null;
function currentLang() {
  if (i18nLang) return i18nLang;
  try { i18nLang = localStorage.getItem("dash-lang") === "en" ? "en" : "zh"; } catch (e) { i18nLang = "zh"; }
  return i18nLang;
}

function dateLocale() {
  return currentLang() === "en" ? "en-AU" : "zh-CN";
}

// Reverse index of the dictionary, built once. Replaces the old per-node
// Object.keys(en).find(...) linear scan. First key wins, as before.
let EN2ZH = null;
function buildReverseMap() {
  const map = Object.create(null);
  const en = I18N.en;
  const keys = Object.keys(en);
  for (let i = 0; i < keys.length; i++) {
    const value = en[keys[i]];
    if (value && map[value] === undefined) map[value] = keys[i];
  }
  return map;
}

const i18nMemo = { zh: new Map(), en: new Map() };

// Translate a whole string. Exact dictionary match, then reverse match, then
// phrase regexes. Anything else is returned BYTE-IDENTICAL -- that is the
// safety net for tenant data (bank names, remarks, customer names). There is
// deliberately no substring replacement: the old i18nReplaceParts rewrote any
// dictionary word found anywhere in any string, which mangled UI copy into
// hybrids ("新增银行账户" -> "AddBank账户") and corrupted real data
// ("Public Bank Amy" -> "Public 银行 Amy" in Chinese mode).
function translateString(raw, lang) {
  if (raw == null) return raw;
  const source = String(raw);
  const trimmed = source.trim();
  if (!trimmed) return source;

  const cache = i18nMemo[lang] || i18nMemo.zh;
  let out = cache.get(trimmed);
  if (out === undefined) {
    out = null;
    if (I18N.zh[trimmed] !== undefined) {
      out = (I18N[lang] && I18N[lang][trimmed]) || trimmed;
    } else {
      if (!EN2ZH) EN2ZH = buildReverseMap();
      const key = EN2ZH[trimmed];
      if (key !== undefined) out = (I18N[lang] && I18N[lang][key]) || key;
    }
    if (out === null) {
      const list = lang === "en" ? I18N_PHRASES : I18N_PHRASES_ZH;
      for (let i = 0; i < list.length; i++) {
        if (list[i][0].test(trimmed)) { out = trimmed.replace(list[i][0], list[i][1]); break; }
      }
    }
    if (cache.size > 8000) cache.clear();
    cache.set(trimmed, out);
  }
  if (out === null || out === trimmed) return source;
  return source.replace(trimmed, out);
}

// Kept for backwards compatibility; both used to be separate code paths.
function i18nText(value, lang) { return translateString(value, lang); }
function i18nPhrase(value, lang) { return translateString(value, lang); }

function visitText(node, lang) {
  let state = textState.get(node);
  if (!state || node.nodeValue !== state.out) {
    // First sight, or a page script overwrote our output: whatever is there
    // now is the authoritative source.
    state = { src: node.nodeValue, out: null };
    textState.set(node, state);
  }
  const next = translateString(state.src, lang);
  if (node.nodeValue !== next) node.nodeValue = next;
  state.out = next;
}

function visitAttrs(el, lang) {
  let bag = null;
  for (let i = 0; i < I18N_ATTRS.length; i++) {
    const attr = I18N_ATTRS[i];
    if (!el.hasAttribute(attr)) continue;
    const cur = el.getAttribute(attr);
    if (!bag) bag = attrState.get(el) || {};
    let state = bag[attr];
    if (!state || cur !== state.out) state = bag[attr] = { src: cur, out: null };
    const next = translateString(state.src, lang);
    if (cur !== next) el.setAttribute(attr, next);
    state.out = next;
  }
  if (bag) attrState.set(el, bag);
}

// translate="no" prunes the whole subtree in O(1). It is the standard HTML
// attribute, so it also stops the browser's own auto-translate from rewriting
// the operator's ledger.
function walk(node, lang) {
  if (!node) return;
  if (node.nodeType === 3) { visitText(node, lang); return; }
  if (node.nodeType !== 1) return;
  if (I18N_SKIP_TAGS.test(node.tagName)) return;
  if (node.getAttribute("translate") === "no") return;
  visitAttrs(node, lang);
  for (let child = node.firstChild; child; child = child.nextSibling) walk(child, lang);
}

function isIsolated(node) {
  const el = node.nodeType === 1 ? node : node.parentElement;
  return !!(el && el.closest && el.closest('[translate="no"]'));
}

// Queue only the ROOTS of changed subtrees: a tbody repaint of 500 rows costs
// 500 entries, not 500 full-document passes. Walking up to check ancestors is
// O(depth), not O(queue).
function markDirty(node) {
  if (!node) return;
  const type = node.nodeType;
  if (type !== 1 && type !== 3) return;
  if (i18nDirty.has(node)) return;
  for (let parent = node.parentNode; parent; parent = parent.parentNode) {
    if (i18nDirty.has(parent)) return;
  }
  i18nDirty.add(node);
}

function onI18nMutations(records) {
  for (let i = 0; i < records.length; i++) {
    const record = records[i];
    if (record.type === "childList") {
      for (let j = 0; j < record.addedNodes.length; j++) markDirty(record.addedNodes[j]);
    } else if (record.type === "characterData") {
      const state = textState.get(record.target);
      if (!state || record.target.nodeValue !== state.out) markDirty(record.target);
    } else if (record.type === "attributes") {
      const bag = attrState.get(record.target);
      const state = bag && bag[record.attributeName];
      if (!state || record.target.getAttribute(record.attributeName) !== state.out) markDirty(record.target);
    }
  }
  if (i18nDirty.size) scheduleI18n();
}

// rAF runs after the mutating task but before that frame is painted, so a
// freshly rendered Chinese row is translated before the user can see it. It
// also cannot be starved the way the old clearTimeout/setTimeout pair was --
// animateValue writes textContent every ~16ms, which reset the 40ms timer
// ~33 times in a row and delayed translation for the whole animation.
function scheduleI18n() {
  if (i18nScheduled) return;
  i18nScheduled = true;
  if (typeof requestAnimationFrame === "function" && !document.hidden) requestAnimationFrame(flushI18n);
  else setTimeout(flushI18n, 0);
}

function flushI18n() {
  i18nScheduled = false;
  const lang = currentLang();
  const roots = i18nDirty;
  i18nDirty = new Set();
  const full = i18nFullPass;
  i18nFullPass = false;

  if (full) {
    if (document.body) walk(document.body, lang);
    applyTitle(lang);
    syncToggleUi(lang);
  } else {
    roots.forEach(function (node) {
      if (node.isConnected === false) return;
      if (isIsolated(node)) return;
      walk(node, lang);
    });
  }
  // Our own writes produced records; visitText/visitAttrs would no-op on them,
  // but draining keeps the queue short.
  if (i18nObserver) i18nObserver.takeRecords();
}

// The old TreeWalker was rooted at document.body, so the tab caption stayed
// Chinese forever. Title format is "<page> - NXC Report" (the brand has no
// dictionary entry, so it passes through untouched in both languages).
function applyTitle(lang) {
  if (!i18nTitleState || document.title !== i18nTitleState.out) {
    i18nTitleState = { src: document.title, out: null };
  }
  const src = i18nTitleState.src;
  const parts = /^(.*?)\s+-\s+(.*)$/.exec(src);
  const next = parts
    ? translateString(parts[1], lang) + " - " + translateString(parts[2], lang)
    : translateString(src, lang);
  if (document.title !== next) document.title = next;
  i18nTitleState.out = next;
}

function syncToggleUi(lang) {
  const btn = document.getElementById("lang-toggle");
  if (!btn) return;
  btn.querySelectorAll("[data-lang-choice]").forEach(function (item) {
    item.classList.toggle("active", item.getAttribute("data-lang-choice") === lang);
  });
  const label = translateString("切换语言", lang);
  btn.setAttribute("aria-label", label);
  btn.setAttribute("title", label);
}

function applyLanguage(lang) {
  const normalized = lang === "en" ? "en" : "zh";
  i18nLang = normalized;
  document.documentElement.setAttribute("lang", normalized === "en" ? "en" : "zh-CN");
  document.documentElement.setAttribute("data-lang", normalized);
  try { localStorage.setItem("dash-lang", normalized); } catch (e) {}
  i18nFullPass = true;
  i18nScheduled = false;
  flushI18n(); // synchronous: the user clicked, a frame of delay reads as lag
}

function setLanguage(next) {
  applyLanguage(next);
  window.dispatchEvent(new CustomEvent("language-changed", { detail: { lang: currentLang() } }));
}

function setupLanguage() {
  // No initial applyLanguage() here: the boot script at the end of <body> has
  // already run one full pass, before the CDN scripts block the first paint.
  const btn = document.getElementById("lang-toggle");
  if (btn) {
    btn.addEventListener("click", function () {
      setLanguage(currentLang() === "en" ? "zh" : "en");
    });
  }
  syncToggleUi(currentLang());
  observeLanguageChanges();
}

function observeLanguageChanges() {
  if (!document.body) return;
  if (!i18nObserver) i18nObserver = new MutationObserver(onI18nMutations);
  i18nObserver.observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: I18N_ATTRS });
}


// Browser globals (guarded so Node can require this file in tests).
if (typeof window !== "undefined") {
  window.dashLang = currentLang;
  window.dashT = function (value) { return translateString(value, currentLang()); };
  window.dashDateLocale = dateLocale;
  window.dashSetLang = setLanguage;
  // Called by a small inline script at the end of <body>, ahead of the CDN
  // <script>s, so the first paint is already in the saved language.
  window.dashI18nApply = function () { applyLanguage(currentLang()); };
}

if (typeof module !== "undefined" && module.exports) {
  module.exports = {
    I18N, I18N_ATTRS, I18N_PHRASES, I18N_PHRASES_ZH,
    currentLang, dateLocale, buildReverseMap, translateString, i18nText, i18nPhrase,
  };
}
