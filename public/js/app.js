function unlockPlatformPendingAudio() {
  if (bankPendingSound.unlocked) return;
  const audio = getBankPendingAudio();
  const muted = audio.muted;
  audio.muted = true;
  const played = audio.play();
  if (played && typeof played.then === "function") {
    played
      .then(function () {
        audio.pause();
        audio.currentTime = 0;
        audio.muted = muted;
        bankPendingSound.unlocked = true;
      })
      .catch(function () {
        audio.muted = muted;
      });
  } else {
    audio.muted = muted;
    bankPendingSound.unlocked = true;
  }
}

