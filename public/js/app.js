function currentLang() {
  try { return localStorage.getItem("dash-lang") === "en" ? "en" : "zh"; } catch (e) { return "zh"; }
}

function i18nText(value, lang) {
  const raw = String(value == null ? "" : value);
  const trimmed = raw.trim();
  if (!trimmed) return raw;
  const zh = I18N.zh;
  const en = I18N.en;
  let key = zh[trimmed] != null ? trimmed : null;
  if (!key) {
    key = Object.keys(en).find(function (k) { return en[k] === trimmed; }) || null;
  }
  if (key) {
    const next = (I18N[lang] && I18N[lang][key]) || key;
    return raw.replace(trimmed, next);
  }
  return i18nReplaceParts(raw, lang);
}

function escapeRegExp(s) {
  return String(s).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function i18nReplaceParts(raw, lang) {
  const zh = I18N.zh;
  const en = I18N.en;
  let out = String(raw == null ? "" : raw);
  if (lang === "en") {
    Object.keys(en)
      .filter(function (k) { return k && en[k] && k.length > 1; })
      .sort(function (a, b) { return b.length - a.length; })
      .forEach(function (k) {
        out = out.replace(new RegExp(escapeRegExp(k), "g"), en[k]);
      });
  } else {
    Object.keys(en)
      .filter(function (k) { return k && en[k] && en[k].length > 3; })
      .sort(function (a, b) { return en[b].length - en[a].length; })
      .forEach(function (k) {
        out = out.replace(new RegExp(escapeRegExp(en[k]), "g"), zh[k] || k);
      });
  }
  return out;
}

function i18nPhrase(value, lang) {
  const raw = String(value == null ? "" : value);
  const trimmed = raw.trim();
  if (!trimmed) return raw;
  const list = lang === "en" ? I18N_PHRASES : I18N_PHRASES_ZH;
  for (const pair of list) {
    if (pair[0].test(trimmed)) return raw.replace(trimmed, trimmed.replace(pair[0], pair[1]));
  }
  return i18nText(raw, lang);
}

function applyLanguage(lang) {
  const normalized = lang === "en" ? "en" : "zh";
  i18nApplying = true;
  if (i18nObserver) i18nObserver.disconnect();
  document.documentElement.setAttribute("lang", normalized === "en" ? "en" : "zh-CN");
  document.documentElement.setAttribute("data-lang", normalized);
  try { localStorage.setItem("dash-lang", normalized); } catch (e) {}

  const walker = document.createTreeWalker(document.body || document.documentElement, NodeFilter.SHOW_TEXT, {
    acceptNode: function (node) {
      const parent = node.parentElement;
      if (!parent || /^(SCRIPT|STYLE|TEXTAREA)$/.test(parent.tagName)) return NodeFilter.FILTER_REJECT;
      if (!node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    },
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach(function (node) {
    const next = i18nPhrase(node.nodeValue, normalized);
    if (node.nodeValue !== next) node.nodeValue = next;
  });
  document.querySelectorAll("*").forEach(function (el) {
    I18N_ATTRS.forEach(function (attr) {
      if (!el.hasAttribute(attr)) return;
      const next = i18nPhrase(el.getAttribute(attr), normalized);
      if (el.getAttribute(attr) !== next) el.setAttribute(attr, next);
    });
  });

  const btn = document.getElementById("lang-toggle");
  if (btn) {
    btn.querySelectorAll("[data-lang-choice]").forEach(function (item) {
      item.classList.toggle("active", item.getAttribute("data-lang-choice") === normalized);
    });
    btn.setAttribute("aria-label", i18nText("切换语言", normalized));
    btn.setAttribute("title", i18nText("切换语言", normalized));
  }
  i18nApplying = false;
  observeLanguageChanges();
}

function scheduleLanguageApply() {
  if (i18nApplying) return;
  clearTimeout(i18nTimer);
  i18nTimer = setTimeout(function () { applyLanguage(currentLang()); }, 40);
}

function setupLanguage() {
  applyLanguage(currentLang());
  const btn = document.getElementById("lang-toggle");
  if (btn) {
    btn.addEventListener("click", function () {
      applyLanguage(currentLang() === "en" ? "zh" : "en");
      window.dispatchEvent(new CustomEvent("language-changed", { detail: { lang: currentLang() } }));
    });
  }
  observeLanguageChanges();
}

function observeLanguageChanges() {
  if (!document.body) return;
  if (!i18nObserver) i18nObserver = new MutationObserver(scheduleLanguageApply);
  i18nObserver.disconnect();
  if (!i18nApplying) {
    i18nObserver.observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: I18N_ATTRS });
  }
}

